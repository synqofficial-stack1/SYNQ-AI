-- Test accounts and records are discarded, and no external services are called.
begin;
do $$
declare a uuid:=gen_random_uuid();b uuid:=gen_random_uuid();c uuid:=gen_random_uuid();d uuid:=gen_random_uuid();
 org uuid;other_org uuid;deal uuid;member_deal uuid;v jsonb;stamp timestamptz;n integer;
begin
 insert into auth.users(id,email)values(a,a||'@example.invalid'),(b,b||'@example.invalid'),(c,c||'@example.invalid'),(d,d||'@example.invalid');
 perform set_config('request.jwt.claim.sub',a::text,true);set local role authenticated;
 v:=public.setup_workspace('QA owner','Sales QA '||a,true);org:=(v->'membership'->>'organization_id')::uuid;reset role;
 perform set_config('request.jwt.claim.sub',c::text,true);set local role authenticated;
 v:=public.setup_workspace('Other owner','Sales other '||c,true);other_org:=(v->'membership'->>'organization_id')::uuid;reset role;
 perform set_config('request.jwt.claim.sub',b::text,true);set local role authenticated;
 perform public.setup_workspace('Member','Sales QA '||a,false);reset role;
 perform set_config('request.jwt.claim.sub',d::text,true);set local role authenticated;
 perform public.setup_workspace('Pending','Sales QA '||a,false);reset role;
 perform set_config('request.jwt.claim.sub',a::text,true);set local role authenticated;
 perform public.review_organization_member(b,'approve');
 insert into public.sales_deals(user_id,title,amount,next_action,next_action_on)values(a,'QA opportunity',1250.50,'Send quotation',current_date) returning id,updated_at into deal,stamp;
 insert into public.sales_targets(organization_id,month,revenue_goal,deals_goal)values(org,date_trunc('month',current_date)::date,10000,2);
 update public.sales_targets set revenue_goal=11000 where organization_id=org;
 update public.sales_deals set stage='won' where id=deal;
 if not exists(select 1 from public.sales_deals where id=deal and closed_at is not null)then raise exception 'Won date not recorded';end if;
 update public.sales_deals set stage='interested' where id=deal;
 if not exists(select 1 from public.sales_deals where id=deal and closed_at is null)then raise exception 'Reopened deal still counted as won';end if;
 update public.sales_deals set notes='Stale write' where id=deal and updated_at=stamp;
 get diagnostics n=row_count;if n<>0 then raise exception 'Stale edit was not detected';end if;
 begin update public.sales_deals set stage='lost',lost_reason='' where id=deal;raise exception 'Lost reason not required';exception when check_violation then null;end;
 begin update public.sales_deals set next_action='',next_action_on=current_date where id=deal;raise exception 'Empty dated task accepted';exception when check_violation then null;end;
 reset role;
 perform set_config('request.jwt.claim.sub',b::text,true);set local role authenticated;
 if not exists(select 1 from public.sales_deals where id=deal)then raise exception 'Approved teammate cannot see deal';end if;
 update public.sales_deals set meeting_on=current_date,meeting_time='14:30',meeting_notes='Demo booked',quote_text='QA draft only' where id=deal;
 get diagnostics n=row_count;if n<>1 then raise exception 'Shared editing failed';end if;
 insert into public.sales_deals(user_id,title)values(b,'Member opportunity')returning id into member_deal;
 begin update public.sales_deals set organization_id=other_org where id=deal;raise exception 'Tenant reassignment allowed';exception when insufficient_privilege then null;end;
 begin update public.sales_deals set user_id=b where id=deal;raise exception 'Authorship reassignment allowed';exception when insufficient_privilege then null;end;
 begin insert into public.sales_deals(user_id,organization_id,title)values(b,other_org,'Invalid');raise exception 'Cross-company deal insert allowed';exception when raise_exception then if SQLERRM='Cross-company deal insert allowed' then raise;end if;end;
 update public.sales_targets set revenue_goal=1 where organization_id=org;
 get diagnostics n=row_count;if n<>0 then raise exception 'Teammate changed owner target';end if;
 if (select revenue_goal from public.sales_targets where organization_id=org)<>11000 then raise exception 'Target incorrect';end if;
 reset role;
 perform set_config('request.jwt.claim.sub',c::text,true);set local role authenticated;
 if exists(select 1 from public.sales_deals where id in(deal,member_deal)) or exists(select 1 from public.sales_targets where organization_id=org)then raise exception 'Cross-company data leaked';end if;
 reset role;
 perform set_config('request.jwt.claim.sub',d::text,true);set local role authenticated;
 if exists(select 1 from public.sales_deals where id=deal)then raise exception 'Pending member read company deal';end if;
 begin insert into public.sales_deals(user_id,title)values(d,'Pending deal');raise exception 'Pending member created deal';exception when not_null_violation or insufficient_privilege then null;end;
 reset role;
 perform set_config('request.jwt.claim.sub',a::text,true);set local role authenticated;
 perform public.review_organization_member(b,'remove');reset role;
 perform set_config('request.jwt.claim.sub',b::text,true);set local role authenticated;
 if exists(select 1 from public.sales_deals where id in(deal,member_deal))then raise exception 'Removed member retained deal access';end if;
 update public.sales_deals set quote_text='Unauthorized' where id=deal;
 get diagnostics n=row_count;if n<>0 then raise exception 'Removed member edited quote';end if;
 reset role;
 raise notice 'Sales company isolation, editing, targets, and removal checks passed';
end;$$;
rollback;
